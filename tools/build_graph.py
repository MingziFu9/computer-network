def main():
    text = GLOSSARY.read_text(encoding="utf-8")
    nodes, chapters, chdirs = [], [""], [""]
    yml = (ROOT / "course.yml").read_text(encoding="utf-8")
    for d, short in re.findall(r"\{dir: (\S+), title: [^,]+, short: ([^,]+),", yml):
        chdirs.append(d)
        chapters.append(short.strip())
    cat_of = {t.replace("_", " "): i for i, ts in enumerate(CATS.values()) for t in ts.split()}
    for sec in re.split(r"\n## ", text)[1:]:
        m = re.match(r"第 (\d+) 章", sec)
        if not m:
            continue
        ch = int(m.group(1))
        for name, en, defi in re.findall(r'\| <span id="g-[^"]+"></span>([^|]*?) \| ([^|]*) \| ([^|]*) \|', sec):
            if name not in cat_of:
                raise SystemExit(f"术语“{name}”没有在 CATS 中归类")
            nodes.append({"id": name, "ch": ch, "cat": cat_of[name], "a": anchor_id(name), "d": defi.strip()})
    ids = {n["id"] for n in nodes}
    edges = []
    for n in nodes:
        key = n["id"].replace(" ", "_")
        if key not in PRE:
            raise SystemExit(f"术语“{n['id']}”没有在 PRE 中写先修")
        for p in PRE[key].split():
            p = p.replace("_", " ")
            if p not in ids:
                raise SystemExit(f"“{n['id']}”的先修“{p}”不在术语表里")
            edges.append([p, n["id"]])
    out = ["// 学习图谱数据：由 tools/build_graph.py 根据附录术语表和先修关系生成，请勿手改",
           "// 改完后运行 python tools/graph_text.py，检查数据并更新 index.md 里的文字版",
           "var CATS = " + json.dumps(list(CATS), ensure_ascii=False) + ";",
           "var CHAPTERS = " + json.dumps(chapters, ensure_ascii=False) + ";",
           "var CHDIRS = " + json.dumps(chdirs, ensure_ascii=False) + ";",
           "var NODES = [\n" + ",\n".join("  " + json.dumps(n, ensure_ascii=False) for n in nodes) + "\n];",
           "var EDGES = " + json.dumps(edges, ensure_ascii=False) + ";", ""]
    (DOCS / "learning-graph/data.js").write_text("\n".join(out), encoding="utf-8")
    print(f"学习图谱：{len(nodes)} 个概念，{len(edges)} 条先修关系，{len(CATS)} 个类别")


if __name__ == "__main__":
    main()
